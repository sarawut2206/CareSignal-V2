/* ---------- ข้อเท็จจริงที่อ่านสด ---------- */
export function facts() {
  const audit = run("node audit/cs-audit.mjs");
  const layers = [...audit.matchAll(/ชั้น (\d): (\d+)\/(\d+) ผ่าน(?:\s+← (.*))?/g)].map((m) => ({ n: +m[1], pass: +m[2], tot: +m[3], fail: m[4] || "" }));
  const unver = [...rd("audit/cs-audit.mjs").matchAll(/\["(U-0\d)", "([^"]+)",\s*\n\s*"([^"]+)"\]/g)].map((m) => [m[1], m[2], m[3]]);
  /* ตัวคั่นเป็นแท็บ (%x09) — ถ้าใช้ | เชลล์ของ Windows จะตีความเป็น pipe แล้วได้ผลว่าง */
  const log = run("git log --pretty=format:%h%x09%ad%x09%s --date=format:%d/%m -12").split("\n").filter(Boolean).map((l) => l.split("\t"));
  const sw = (rd("sw.js").match(/caresignal-v(\d+)/) || [])[1] || "?";
  const sql = existsSync(ROOT + "supabase") ? readdirSync(ROOT + "supabase").filter((f) => /^\d+_.*\.sql$/.test(f)).sort() : [];
  let filled = null, nPeople = 0;
  try { const v = JSON.parse(rd("validation/results.json")); filled = !!v.filled; nPeople = (v.people || []).length; } catch (e) {}
  const files = [
    ["CareSignal-App.html", "แอปผู้เอาประกันและครอบครัว (มือถือ)"],
    ["CareSignal-Staff.html", "คอนโซลเจ้าหน้าที่และผู้เชี่ยวชาญ"],
    ["CareSignal-Portfolio-Dashboard.html", "แดชบอร์ดบริษัทประกัน"],
    ["CareSignal-Journey.html", "เดโมเส้นทางหนึ่งเคส"],
    ["CareSignal-Vision.html", "หน้าทดลองกล้อง (รุ่นวิจัย)"],
    ["index.html", "เว็บหน้าแรก 5 ส่วน"],
    ["cs-backend.js", "ตัวเชื่อมฐานข้อมูล Supabase"],
    ["cs-referral-forms.js", "แบบฟอร์มส่งต่อสหวิชาชีพ"],
    ["cs-demo.js", "โหมดสาธิตข้อมูลสังเคราะห์"],
    ["cs-meds.js", "ฐานยาและกลุ่มยาเสี่ยง (FRID)"],
    ["cs-aruco.js", "ตัวอ่านป้ายสัญลักษณ์"],
    ["cs-hospitals.js", "รายชื่อหน่วยบริการทั่วประเทศ"]
  ].map(([f, nm]) => [f, nm, lines(f)]);
  const app = rd("CareSignal-App.html");
  const nRules = ((app.match(/var ENGINE=\{[\s\S]*?rules:\{([\s\S]*?)\n {2}\},/) || ["", ""])[1].match(/(R\d+|B\d+):\{nm:/g) || []).length;
  return { layers, unver, log, sw, sql, filled, nPeople, files, nRules,
    auditPass: layers.filter((l) => l.n !== 6).every((l) => l.pass === l.tot),
    l7: layers.find((l) => l.n === 7) || { pass: 0, tot: 0 } };
}

