def bullets(doc, items, size=14, indent=0.5):
    for it in items:
        if isinstance(it, tuple):
            rich(doc, [("•  ", True, BRAND), (it[0], True, None), (it[1], False, None)], size=size, after=1, indent=indent)
        else:
            rich(doc, [("•  ", True, BRAND), (it, False, None)], size=size, after=1, indent=indent)


def steps(doc, items, size=14):
    for i, (t, d) in enumerate(items, 1):
        rich(doc, [(f"{i}. ", True, BRAND), (t, True, None), ("  " + d if d else "", False, None)], size=size, after=2, indent=0.3)


def flow(doc, boxes, fill="EAF3FC"):
    """แผนภาพลูกศรแนวตั้งแบบตาราง อ่านได้ทั้งใน Word และ PDF"""
    t = doc.add_table(rows=len(boxes) * 2 - 1, cols=1); t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, (title, sub) in enumerate(boxes):
        c = t.rows[i * 2].cells[0]; c.width = Cm(14); shade(c, fill)
        p = c.paragraphs[0]; p.alignment = WD_ALIGN_PARAGRAPH.CENTER; p.paragraph_format.space_after = Pt(0)
        set_font(p.add_run(thai(title)), 14, True, BRAND)
        if sub:
            q = c.add_paragraph(); q.alignment = WD_ALIGN_PARAGRAPH.CENTER; q.paragraph_format.space_after = Pt(1)
            set_font(q.add_run(thai(sub)), 12.5, False, INK2)
        if i < len(boxes) - 1:
            a = t.rows[i * 2 + 1].cells[0]
            p = a.paragraphs[0]; p.alignment = WD_ALIGN_PARAGRAPH.CENTER; p.paragraph_format.space_after = Pt(0)
            set_font(p.add_run("▼"), 12, False, INK2)
    tbl = t._tbl; tblPr = tbl.tblPr
    b = OxmlElement("w:tblBorders")
    for side in ("top", "left", "bottom", "right", "insideH", "insideV"):
        e = OxmlElement("w:" + side); e.set(qn("w:val"), "nil"); b.append(e)
    tblPr.append(b)
    para(doc, "", size=4, after=0)


