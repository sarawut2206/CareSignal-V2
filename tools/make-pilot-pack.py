st.paragraph_format.space_after = Pt(2); st.paragraph_format.line_spacing = 1.0

def run(p, text, bold=False, size=None, color=None, italic=False):
    r = p.add_run(th(text)); r.bold = bold; r.italic = italic
    r.font.name = FONT; r._element.rPr.rFonts.set(qn("w:cs"), FONT)
    r.font.size = Pt(size or 15)
    if size: r._element.rPr.append(OxmlElement("w:szCs")); r._element.rPr[-1].set(qn("w:val"), str(int(size * 2)))
    if color: r.font.color.rgb = RGBColor.from_string(color)
    return r
def para(text="", bold=False, size=None, align=None, indent=None, after=2, color=None):
    p = doc.add_paragraph(); p.paragraph_format.space_after = Pt(after)
    if align == "c": p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    if align == "r": p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    if indent: p.paragraph_format.first_line_indent = Cm(indent)
    if text: run(p, text, bold, size, color)
    return p
def rich(parts, indent=None, after=2):
    """parts = [("ข้อความ", True/False), …] — True = ตัวหนา"""
    p = doc.add_paragraph(); p.paragraph_format.space_after = Pt(after)
    if indent: p.paragraph_format.first_line_indent = Cm(indent)
    for t, b in parts: run(p, t, b)
    return p
def h1(text):
    p = para(text, True, 20, "c", after=6)
    if NEXT_PAGE[0]: p.paragraph_format.page_break_before = True; NEXT_PAGE[0] = False
def h2(text): p = para(text, True, 16, after=2); p.paragraph_format.space_before = Pt(8); p.paragraph_format.keep_with_next = True
def bullet(text, level=0, bold_lead=None):
    p = doc.add_paragraph(style="List Bullet"); p.paragraph_format.space_after = Pt(1)
    p.paragraph_format.left_indent = Cm(1.0 + level * 0.8)
    if bold_lead: run(p, bold_lead, True)
    run(p, text); return p
def numbered(items):
    for i, t in enumerate(items, 1):
        p = doc.add_paragraph(); p.paragraph_format.space_after = Pt(1); p.paragraph_format.left_indent = Cm(1.0); p.paragraph_format.first_line_indent = Cm(-0.6)
        run(p, "%d. " % i); run(p, t)
def shade(cell, hexcolor):
    tcPr = cell._element.get_or_add_tcPr(); s = OxmlElement("w:shd"); s.set(qn("w:val"), "clear"); s.set(qn("w:fill"), hexcolor); tcPr.append(s)
def table(rows, widths, header=True, size=14):
    t = doc.add_table(rows=len(rows), cols=len(rows[0])); t.style = "Table Grid"; t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, r in enumerate(rows):
        for j, v in enumerate(r):
            c = t.cell(i, j); c.width = Cm(widths[j]); c.text = ""
            p = c.paragraphs[0]; p.paragraph_format.space_after = Pt(0)
            run(p, v, bold=(header and i == 0), size=size)
            if header and i == 0: shade(c, "EEF1F5")
    sp = doc.add_paragraph(); sp.paragraph_format.space_after = Pt(0); sp.paragraph_format.line_spacing = Pt(8)   # ช่องว่างหลังตารางแบบบาง
    return t
