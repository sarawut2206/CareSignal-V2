# ---------- ตัดคำไทยด้วย ZWSP ให้บรรทัดเต็ม (ถ้ามี pythainlp) ----------
try:
    from pythainlp.tokenize import word_tokenize
    def th(t):
        out = []
        for part in re.split(r"(\s+)", t):
            if re.search(r"[฀-๿]", part):
                out.append("​".join(word_tokenize(part, keep_whitespace=False)))
            else:
                out.append(part)
        return "".join(out)
except Exception:
    def th(t): return t

