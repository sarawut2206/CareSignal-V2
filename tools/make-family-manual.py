def H1(doc, no, title, sub=None, first=False):
    p = para(doc, th(no) + ". " + title, size=19, bold=True, color=GREEN, after=0, keep=True)
    if not first:
        p.paragraph_format.page_break_before = True
    if sub:
        para(doc, sub, size=13.5, color=INK2, after=0, keep=True)
    rule = doc.add_paragraph(); rule.paragraph_format.space_after = Pt(4)
    set_font(rule.add_run(""), 4)
    ppr = rule._p.get_or_add_pPr(); pb = OxmlElement("w:pBdr"); bt = OxmlElement("w:bottom")
    bt.set(qn("w:val"), "single"); bt.set(qn("w:sz"), "12"); bt.set(qn("w:space"), "1"); bt.set(qn("w:color"), "0B766A")
    pb.append(bt); ppr.append(pb)


def H2(doc, no, title):
    return para(doc, th(no) + " " + title, size=15, bold=True, color=BRAND, before=6, after=2, keep=True)


def steps(doc, items, size=14):
    for i, t in enumerate(items, 1):
        if isinstance(t, tuple):
            rich(doc, [("(" + th(i) + ") ", True, GREEN), (t[0], True, None), (" " + t[1], False, None)], size=size, after=2, indent=0.4)
        else:
            rich(doc, [("(" + th(i) + ") ", True, GREEN), (t, False, None)], size=size, after=2, indent=0.4)


def bullets(doc, items, size=14):
    for t in items:
        if isinstance(t, tuple):
            rich(doc, [("•  ", True, GREEN), (t[0], True, None), (t[1], False, None)], size=size, after=1, indent=0.5)
        else:
            rich(doc, [("•  ", True, GREEN), (t, False, None)], size=size, after=1, indent=0.5)


def shot(doc, name, caption, lines, width=5.2):
    """ภาพหน้าจอด้านซ้าย คำอธิบายด้านขวา"""
    t = doc.add_table(rows=1, cols=2); t.alignment = WD_TABLE_ALIGNMENT.CENTER
    a, b = t.rows[0].cells; a.width = Cm(width + 0.4); b.width = Cm(16.2 - width)
    p = a.paragraphs[0]; p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    f = os.path.join(SHOTS, name + ".png")
    if os.path.exists(f):
        p.add_run().add_picture(f, width=Cm(width))
    q = a.add_paragraph(); q.alignment = WD_ALIGN_PARAGRAPH.CENTER
    set_font(q.add_run(thai(caption)), 11.5, False, INK2)
    first = True
    for ln in lines:
        c = b.paragraphs[0] if first else b.add_paragraph(); first = False
        c.paragraph_format.space_after = Pt(3); c.paragraph_format.line_spacing = 1.0
        if isinstance(ln, tuple):
            set_font(c.add_run(thai(ln[0])), 14, True, GREEN if ln[0].startswith("ข้อ") else None)
            set_font(c.add_run(thai(ln[1])), 14)
        else:
            set_font(c.add_run(thai(ln)), 14)
    para(doc, "", size=4, after=0)


